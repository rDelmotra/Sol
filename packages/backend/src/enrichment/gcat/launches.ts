// ============================================================
// launches.ts — GCAT Launch Lists/launch.tsv → LaunchRecord map
//
// The Launches entity (G2). Keyed by Launch_Tag — the same tag every satcat
// row carries (rec.launchTag; join integrity 100% on the 2026-07 snapshot).
// LV family joins lv.tsv (#LV_Name, 100% verified) and site display names
// join sites.tsv (#Site). Docs: …/gcat/web/launch/lcols.html
//
// LaunchCode grammar: char 1 = category (O orbital, D deep space, S/M/A/…
// suborbital families), char 2 = outcome (S success, F failure, E pad
// explosion, U unknown), optionally followed by partial-assessment digits
// ("OS75" = orbital success at 75%, "OF40" = failure at 40%).
// ============================================================

import { parseGcatTsv } from './tsv.js';

export interface LaunchRecord {
  tag: string;
  date: string;               // raw GCAT vague date
  lvType: string;
  lvFamily: string | null;
  variant: string | null;
  flightId: string | null;
  mission: string | null;
  site: string | null;        // GCAT site code
  siteName: string | null;    // display name from sites.tsv
  pad: string | null;
  platform: string | null;
  agencies: string[];         // org codes ('/'-split, '?' stripped)
  code: string;               // raw LaunchCode ("OS", "OS75", "OF40")
  success: boolean | null;    // char2 only: S→true, F/E→false, else null
  category: string | null;
  group: string | null;
  orbPay: number | null;      // orbital payload tonnage (autogenerated — display only)
}

/** char 2 of the LaunchCode decides the outcome; trailing digits are ignored. */
export function launchSuccess(code: string): boolean | null {
  const c = code[1];
  if (c === 'S') return true;
  if (c === 'F' || c === 'E') return false;
  return null;
}

/** lv.tsv → LV_Name → LV_Family (trimmed; family column is space-padded). */
export function parseLvFamilies(lvText: string): Map<string, string> {
  const { rows } = parseGcatTsv(lvText);
  const out = new Map<string, string>();
  for (const row of rows) {
    if (row.LV_Name && row.LV_Family) out.set(row.LV_Name, row.LV_Family.trim());
  }
  return out;
}

/** sites.tsv → Site code → display name (ShortEName || ShortName || Name). */
export function parseSiteNames(sitesText: string): Map<string, string> {
  const { rows } = parseGcatTsv(sitesText);
  const out = new Map<string, string>();
  for (const row of rows) {
    const name = row.ShortEName || row.ShortName || row.Name;
    if (row.Site && name) out.set(row.Site, name);
  }
  return out;
}

function num(cell: string): number | null {
  if (!cell) return null;
  const n = parseFloat(cell.replace(/\s/g, ''));
  return Number.isFinite(n) ? n : null;
}

/**
 * Parse launch.tsv into LaunchRecords (ALL rows — the build filters to
 * launches referenced by cataloged objects before writing launches.json).
 */
export function parseGcatLaunches(
  launchText: string,
  lvFamilies: Map<string, string>,
  siteNames: Map<string, string>,
): Map<string, LaunchRecord> {
  const { rows } = parseGcatTsv(launchText);
  const out = new Map<string, LaunchRecord>();
  for (const row of rows) {
    const tag = row.Launch_Tag?.trim();
    if (!tag) continue;
    const code = row.LaunchCode ?? '';
    const site = row.Launch_Site || null;
    out.set(tag, {
      tag,
      date: row.Launch_Date ?? '',
      lvType: row.LV_Type ?? '',
      lvFamily: lvFamilies.get(row.LV_Type ?? '') ?? null,
      variant: row.Variant || null,
      flightId: row.Flight_ID || null,
      mission: row.Mission || null,
      site,
      siteName: site ? siteNames.get(site) ?? null : null,
      pad: row.Launch_Pad || null,
      platform: row.Platform || null,
      agencies: (row.Agency ?? '')
        .split('/')
        .map((a) => a.trim().replace(/\?$/, ''))
        .filter(Boolean),
      code,
      success: launchSuccess(code),
      category: row.Category || null,
      group: row.Group || null,
      orbPay: num(row.OrbPay ?? ''),
    });
  }
  return out;
}
