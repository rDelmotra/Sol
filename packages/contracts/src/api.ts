import type { Sector } from './enums.js';
import type { EnrichedTLEObject } from './tle.js';
import type { ObjectMetadata } from './metadata.js';

// ── /api/tle/all + /api/history/at ─────────────────────────────────────────
// Identical envelope on both routes (history/serving/snapshot-cache.ts's
// buildDaySnapshot comment: "Same envelope as /api/tle/all... Response shape
// is identical... so the client re-seeds with zero special-casing"). The
// frontend previously hand-duplicated this as history-client.ts's
// `HistoryAtResponse` (byte-identical fields) — merged, no diff.
export interface CatalogResponse {
  version: string;
  count: number;
  data: EnrichedTLEObject[];
}

// ── /api/history/coverage ───────────────────────────────────────────────────
// backend history/types.ts and frontend data/history-client.ts each declared
// this independently; diffed field-by-field — zero differences.
export interface HistoryCoverage {
  from: string | null;          // earliest UTC day 'YYYY-MM-DD' (null if empty)
  to: string | null;            // latest UTC day 'YYYY-MM-DD'
  objectCount: number;          // distinct objects in object_dim
  lastIngestAt: string | null;  // ISO of the most recent ingest
}

// ── /api/tle/visual ──────────────────────────────────────────────────────────
export type VisualDataSource = 'celestrak' | 'cache';

// Backend's routes/tle-visual.ts named this `VisualEndpointResponse`; the
// frontend's data/visualList.ts independently declared a defensive,
// all-`unknown` `VisualListApiResponse` for runtime validation of the same
// wire shape (missing `count`, which the frontend reader never used). Merged
// as the typed (non-`unknown`) shape the backend actually sends; the frontend
// parser now narrows from `Partial<VisualListResponse>` instead of its own
// all-`unknown` interface — same runtime behavior (still checks each field
// before trusting it), fewer hand-typed fields.
export interface VisualListResponse {
  version: string;
  count: number;
  ids: number[];
  source: VisualDataSource;
  stale: boolean;
}

// ── /api/query/vocab ─────────────────────────────────────────────────────────
// backend enrichment/query-vocab.ts's `QueryVocabArtifact` and frontend
// data/query-vocab-client.ts's `QueryVocab` — diffed field-by-field, zero
// differences (both: launches/orgs/owners, same field shapes). Named `QueryVocab`
// here (the frontend's name) since that's the name query/vocab.ts's public API
// already surfaces throughout the frontend query tier.
export interface QueryVocab {
  /** tag → [lvFamily, siteName, agencyCodes] (nulls/[] preserved — positional). */
  launches: Record<string, [string | null, string | null, string[]]>;
  /** org code → { n: name, a?: alias variants, p?: parent code } (owners + agencies + ancestors). */
  orgs: Record<string, { n: string; a?: string[]; p?: string }>;
  /** Codes that own >=1 in-orbit object — distinguishes operator vs agency-only names. */
  owners: string[];
}

// ── GCAT Launches entity (launches.json / GET /api/launch/:tag) ─────────────
// Moved verbatim from backend enrichment/gcat/launches.ts (source of truth —
// the frontend never declared its own copy of the base record, only the
// `agencyNames`-extended read-model below).
export interface LaunchRecord {
  tag: string;
  date: string;               // raw GCAT vague date
  lvType: string;
  lvFamily: string | null;
  variant: string | null;
  flightId: string | null;
  mission: string | null;
  site: string | null;        // GCAT site code
  siteName: string | null;    // display name from sites.tsv
  pad: string | null;
  platform: string | null;
  agencies: string[];         // org codes ('/'-split, '?' stripped)
  code: string;               // raw LaunchCode ("OS", "OS75", "OF40")
  success: boolean | null;    // char2 only: S->true, F/E->false, else null
  category: string | null;
  group: string | null;
  orbPay: number | null;      // orbital payload tonnage (autogenerated — display only)
}

// ── GCAT Organizations entity (orgs.json / GET /api/org/:code) ──────────────
// Moved verbatim from backend enrichment/gcat/orgs.ts (source of truth). The
// frontend's old `OrgInfo` (metadata-types.ts) was missing `aliases?` — a real
// field the backend sends whenever an org record has alias name variants; that
// field is now included (frontend never read `OrgInfo`, so this only widens
// the type, no behavior change). `OrgInfo` itself had zero importers outside
// metadata-types.ts and is dropped rather than kept as a dead re-export.
export interface OrgRecord {
  code: string;
  name: string;               // display pick: EName || ShortEName || ShortName || Name
  aliases?: string[];         // remaining name variants (search vocab, G3)
  stateCode: string | null;   // GCAT state code (canonicalize at use sites)
  cls: string | null;         // raw Class (B/D/C/A)
  sectors: Sector[];          // Class folded like psatcat Clas (A->civil)
  type: string | null;        // raw Type flags ("O/PL", "LA", …)
  parent: string | null;      // org hierarchy (another org code)
  lat: number | null;
  lon: number | null;
  tstart: string | null;
  tstop: string | null;
}

/** `GET /api/metadata/:noradId`'s embedded `launch` field: a LaunchRecord plus
 *  the resolved agency display names composed at request time (routes/metadata.ts).
 *  NOTE: `GET /api/launch/:tag` sends the bare `LaunchRecord` (no agencyNames). */
export type LaunchInfo = LaunchRecord & {
  /** Resolved agency display names — embedded by the metadata route. */
  agencyNames?: string[];
};

/** Slim org reference embedded in `ObjectMetadataResponse` (routes/metadata.ts's
 *  `orgRef()` helper) — NOT the full `OrgRecord` served by `GET /api/org/:code`. */
export interface OrgRef {
  code: string;
  name: string;
  sectors: Sector[];
}

/** `GET /api/metadata/:noradId` — the join record plus composed launch/org
 *  context (routes/metadata.ts). */
export type ObjectMetadataResponse = ObjectMetadata & {
  launch?: LaunchInfo;
  ownerOrg?: OrgRef;
  manufacturerOrg?: OrgRef;
};
